package cz.martim12.noteindex.gui.settings;

/**
 * Available application theme selection modes.
 */
public enum ThemePreference {

    /**
     * Follows the operating system appearance preference.
     */
    SYSTEM,

    /**
     * Always uses the light application theme.
     */
    LIGHT,

    /**
     * Always uses the dark application theme.
     */
    DARK
}
